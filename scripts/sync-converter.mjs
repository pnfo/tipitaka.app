// node scripts/sync-converter.mjs [--check] - copies @pnfo/pali-converter (the one script converter, shared with
// open.tipitaka.lk) into server/convert/pali-converter.js as a plain script for goja (SSR in Go).
// --check fails when the copy is out of date (CI).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const pkgDir = path.dirname(require.resolve('@pnfo/pali-converter/package.json'))
const src = fs.readFileSync(path.join(pkgDir, 'index.js'), 'utf8')
const lock = JSON.parse(fs.readFileSync(path.join(repo, 'package-lock.json'), 'utf8'))
const resolved = lock.packages['node_modules/@pnfo/pali-converter']?.resolved ?? 'unknown'
let out = src.replace(/^export\s+(const|function|class|let|var)\s/gm, '$1 ')
if (/^\s*(import|export)\s/m.test(out)) throw new Error('unexpected module syntax in the converter')
out = `// generated by scripts/sync-converter.mjs from ${resolved} - do not edit\n${out}`
const dest = path.join(repo, 'server/convert/pali-converter.js')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) { console.error('server/convert/pali-converter.js is out of date: node scripts/sync-converter.mjs'); process.exit(1) }
} else {
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, out)
  console.log('wrote', path.relative(repo, dest), out.length)
}
